/** Классифицирует число по трём формам русского множественного. */
function pluralClass(n: number): 'one' | 'few' | 'many' {
  const abs = Math.abs(n);
  const mod100 = abs % 100;
  const mod10 = abs % 10;
  if (mod100 >= 11 && mod100 <= 14) return 'many';
  if (mod10 === 1) return 'one';
  if (mod10 >= 2 && mod10 <= 4) return 'few';
  return 'many';
}

/** Форматирование числа тенге неразрывными пробелами: `1 000 000 ₸`. */
export function money(v: number): string {
  return `${v.toLocaleString('ru-RU').replace(/\s/g, ' ')} ₸`;
}

const MONTHS_GEN = [
  'января',
  'февраля',
  'марта',
  'апреля',
  'мая',
  'июня',
  'июля',
  'августа',
  'сентября',
  'октября',
  'ноября',
  'декабря',
];

/** `2026-10-16` → `16 октября`. */
export function humanDate(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!m) return iso;
  const day = parseInt(m[3], 10);
  const month = parseInt(m[2], 10) - 1;
  return `${day} ${MONTHS_GEN[month] ?? ''}`.trim();
}

